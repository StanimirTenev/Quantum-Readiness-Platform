def test_future_graph_snapshot_loader_contract_rejects_remote_url_like_paths():
    with pytest.raises(GraphSnapshotUnsafePathError, match="graph_snapshot_unsafe_path"):
        load_graph_snapshot("http://example.com/graph.json")

    with pytest.raises(GraphSnapshotUnsafePathError, match="graph_snapshot_unsafe_path"):
        load_graph_snapshot("https://example.com/graph.json")


def test_future_graph_snapshot_loader_contract_does_not_mutate_input_file_content(tmp_path):
    snapshot_path = tmp_path / "snapshot.json"
    original_content = (
        '{"graph_schema_version":"1.0","nodes":[{"id":"n1","type":"service"},{"id":"n2","type":"dataset"}],'
        '"edges":[{"source":"n1","target":"n2","type":"depends_on"}],"warnings":[]}'
    )
    snapshot_path.write_text(original_content, encoding="utf-8")
    before_hash = hashlib.sha256(snapshot_path.read_bytes()).hexdigest()

    _snapshot = load_graph_snapshot(snapshot_path)

    after_hash = hashlib.sha256(snapshot_path.read_bytes()).hexdigest()
    assert before_hash == after_hash
